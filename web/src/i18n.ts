export function triggerName(lang: Lang, id: TriggerId | string, long = false): string {
  if (long) return NAMES.get(id)?.[lang] ?? id;
  return SHORT[id]?.[lang] ?? NAMES.get(id)?.[lang] ?? id;
}

export function reasonKey(kind: ReasonKind): Key {
  return `reason_${kind}` as Key;
}

/** One reason as a sentence: what the label (or the database, or Gemma) says, with the words quoted. */
export function describe(lang: Lang, r: Reason, name: string): string {
  const q = (x: string) => (lang === "ar" ? `«${x}»` : `“${x}”`);
  const vars = { quote: r.quote ? q(r.quote) : "", allergen: r.trigger ? triggerName(lang, r.trigger) : "", by: r.approved_by ?? "", name };
  if (r.source === "open_food_facts") return t(lang, r.kind === "contains" ? "reason_off_contains" : "reason_off_may", vars);
  return t(lang, reasonKey(r.kind), vars);
}

export function levelWord(lang: Lang, l: Level | undefined): string {
  return t(lang, l === "red" ? "levelRedShort" : l === "amber" ? "levelAmberShort" : "levelGreenShort");
}

export function pillWord(lang: Lang, l: Level): string {
  return t(lang, l === "red" ? "pillRed" : l === "amber" ? "pillAmber" : "pillGreen");
}

export function ago(lang: Lang, at: number): string {
  const m = Math.round((Date.now() - at) / 60000);
  if (m < 1) return t(lang, "justNow");
  if (m < 60) return t(lang, "minutesAgo", { n: m });
  if (m < 60 * 24) return t(lang, "hoursAgo", { n: Math.round(m / 60) });
  return t(lang, "daysAgo", { n: Math.round(m / 1440) });
}

export function joinNames(lang: Lang, names: string[]): string {
  if (names.length <= 1) return names[0] ?? "";
  return lang === "ar" ? names.join(" و") : `${names.slice(0, -1).join(", ")} and ${names.at(-1)}`;
}

