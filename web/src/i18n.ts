export function languageName(lang: Lang, code: string | null | undefined): string {
  if (!code) return lang === "ar" ? "لغة غير معروفة" : "language unknown";
  return LANG_NAMES[code.slice(0, 2)]?.[lang] ?? code;
}

export function shortDate(lang: Lang, at: number | string): string {
  return new Date(at).toLocaleDateString(lang === "ar" ? "ar-JO" : "en-GB", { day: "numeric", month: "short", year: "numeric" });
}
